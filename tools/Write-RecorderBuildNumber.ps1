param(
  [Parameter(Mandatory)][string]$CounterPath,
  [Parameter(Mandatory)][string]$OutputPath,
  [long]$BuildNumber
)

$ErrorActionPreference = 'Stop'
$number = $BuildNumber
if ($PSBoundParameters.ContainsKey('BuildNumber')) {
  if ($number -lt 0) { throw 'BuildNumber must be nonnegative.' }
}
else {
  $counter = [IO.Path]::GetFullPath($CounterPath)
  New-Item -ItemType Directory -Force -Path (Split-Path -Parent $counter) | Out-Null
  $stream = $null
  $deadline = [DateTime]::UtcNow.AddSeconds(30)
  while (-not $stream) {
    try {
      $stream = [IO.File]::Open($counter, [IO.FileMode]::OpenOrCreate,
        [IO.FileAccess]::ReadWrite, [IO.FileShare]::None)
    }
    catch [IO.IOException] {
      if ([DateTime]::UtcNow -ge $deadline) { throw 'The recorder build counter is busy.' }
      Start-Sleep -Milliseconds 50
    }
  }
  try {
    $reader = [IO.StreamReader]::new($stream, [Text.Encoding]::UTF8, $true, 1024, $true)
    try { $text = $reader.ReadToEnd().Trim() }
    finally { $reader.Dispose() }
    $previous = [long]0
    if ($text -and (-not [long]::TryParse($text, [ref]$previous) -or $previous -lt 0)) {
      throw 'The recorder build counter is invalid; refusing to reset it.'
    }
    if ($previous -eq [long]::MaxValue) { throw 'The recorder build counter is exhausted.' }
    $number = $previous + 1
    $bytes = [Text.Encoding]::UTF8.GetBytes($number.ToString([Globalization.CultureInfo]::InvariantCulture))
    $stream.Position = 0
    $stream.Write($bytes, 0, $bytes.Length)
    $stream.SetLength($bytes.Length)
    $stream.Flush($true)
  }
  finally { $stream.Dispose() }
}

$output = [IO.Path]::GetFullPath($OutputPath)
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $output) | Out-Null
$literal = $number.ToString([Globalization.CultureInfo]::InvariantCulture)
$source = "// Generated by the recorder build. Do not edit.`r`n[assembly: System.Reflection.AssemblyMetadata(`"UiAtlasBuildNumber`", `"$literal`")]`r`n"
[IO.File]::WriteAllText($output, $source, [Text.UTF8Encoding]::new($false))
Write-Output "UiAtlas recorder build $number"
